import json
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LEDGER = "docs/RUN_LEDGER.jsonl"
HEADER = "<!-- Generated by scripts/index.py; do not edit. Rerun it after a change. -->\n\n"


