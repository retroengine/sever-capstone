def run(*cmd: str) -> str:
    return subprocess.run(cmd, cwd=ROOT, check=True, capture_output=True, text=True).stdout


def tracked() -> list[str]:
    return run("git", "ls-files").splitlines()


def owned(n: int) -> list[str]:
    """The files part ``n`` owns, as ``scripts/freeze.sh list n`` prints them."""
    out = run("bash", "scripts/freeze.sh", "list", str(n))
    return sorted(line.split("  ", 1)[1] for line in out.splitlines() if "  " in line)


def crate_parts() -> dict[str, int]:
    """The ``PART`` map of the architecture test (Build §3.2), read without importing it."""
    src = (ROOT / "tests/architecture/test_architecture.py").read_text(encoding="utf-8")
    for node in ast.walk(ast.parse(src)):
        if isinstance(node, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id == "PART" for t in node.targets
        ):
            value = ast.literal_eval(node.value)
            if isinstance(value, dict):
                return {str(k): int(v) for k, v in value.items()}
    raise SystemExit("PART map not found in tests/architecture/test_architecture.py")


def tag(n: int) -> str:
    tags = sorted(t for t in run("git", "tag", "-l", f"part-{n}-frozen*").split() if t)
    return tags[-1] if tags else ""


def ledger() -> list[dict[str, object]]:
    text = (ROOT / LEDGER).read_text(encoding="utf-8")
    return [json.loads(line) for line in text.splitlines() if line.strip()]


def step_of(row: dict[str, object]) -> str:
    words = str(row.get("command", "")).split()
    if len(words) >= 2 and words[0] == "gates":
        return words[1]
    if words[:1] == ["fair"]:
        return "fair " + (words[1] if len(words) > 1 else "")
    return " ".join(words[:2])


def part_of(row: dict[str, object]) -> int | None:
    # P4-T13 is Part 1's quantisation measure, unchanged, at nq-1m (T-6, Build 3-4 §2.10).
    if step_of(row) == "p1-quant-recall" and row.get("data") == "nq-1m":
        return 4
    m = re.match(r"p([1-4])-", step_of(row))
    if m:
        return int(m.group(1))
    p = str(row.get("part", ""))
    return int(p) if p in {"1", "2", "3", "4"} else None


def finished(rows: list[dict[str, object]]) -> list[dict[str, object]]:
    """Ledger rows with an outcome (``started`` rows are only the opening line of a run)."""
    return [r for r in rows if r.get("outcome") != "started"]


# --- counting tests -----------------------------------------------------------------------


RUST_TEST = re.compile(r"^\s*#\[(?:test|tokio::test)\]", re.MULTILINE)
PROPTEST_FN = re.compile(r"^\s*fn\s+\w+\s*\(.*\bin\b", re.MULTILINE)
PY_TEST = re.compile(r"^\s*(?:async\s+)?def\s+test_\w*\s*\(", re.MULTILINE)


def count(files: list[str]) -> tuple[int, int]:
    """(Rust test functions, Python test functions) in ``files``."""
    rust = py = 0
    for f in files:
        p = ROOT / f
        if f.endswith(".rs"):
            text = p.read_text(encoding="utf-8", errors="replace")
            rust += len(RUST_TEST.findall(text))
            if "proptest!" in text:
                rust += len(PROPTEST_FN.findall(text))
        elif f.endswith(".py") and ("/tests/" in f or Path(f).name.startswith("test_")):
            py += len(PY_TEST.findall(p.read_text(encoding="utf-8", errors="replace")))
    return rust, py


def under(files: list[str], prefix: str) -> list[str]:
    prefix = prefix.rstrip("/") + "/"
    return [f for f in files if f.startswith(prefix)]


@dataclass(frozen=True)
class Place:
    path: str
    kind: str
    rust: int
    py: int
    files: int


def test_places(n: int, files: list[str], crates: list[str]) -> list[Place]:
    """Where part ``n``'s tests live, each with its kind and counts."""
    mine = set(owned(n))
    places: list[Place] = []
    for c in crates:
        fs = under(files, f"crates/{c}")
        r, _ = count(fs)
        if r:
            places.append(
                Place(f"crates/{c}", "crate tests (unit, property, integration)", r, 0, 0)
            )
    for pkg in sorted({f.split("/")[1] for f in mine if f.startswith("python/") and "/" in f[7:]}):
        fs = under(files, f"python/{pkg}/tests")
        _, p = count(fs)
        if p:
            places.append(Place(f"python/{pkg}/tests", "Python package tests", 0, p, 0))
    loose = sorted(f for f in mine if f.startswith("tests/") and not f.startswith("tests/proofs/"))
    if n == 1:
        loose.append("tests/architecture/test_architecture.py")
    for f in sorted(set(loose)):
        _, p = count([f])
        if p:
            places.append(Place(f, "spec, end-to-end and architecture tests", 0, p, 0))
    fuzz = sorted({f.split("/fuzz_targets/")[0] for f in mine if "/fuzz_targets/" in f})
    for d in fuzz:
        targets = [f for f in mine if f.startswith(f"{d}/fuzz_targets/") and f.endswith(".rs")]
        places.append(Place(f"{d}/fuzz_targets", "fuzz targets", 0, 0, len(targets)))
    proofs = [f for f in files if f.startswith(f"tests/proofs/p{n}/") and f.endswith(".patch")]
    if proofs:
        places.append(
            Place(f"tests/proofs/p{n}", "red proofs (one patch per rule)", 0, 0, len(proofs))
        )
    room = sorted(
        {"/".join(f.split("/")[:3]) for f in files if f.startswith(f"tests/cleanroom/p{n}/")}
    )
    for d in room:
        _, p = count(under(files, d))
        places.append(Place(d, "clean-room tests (fair testing, sealed)", 0, p, 0))
    return places


# --- rendering ----------------------------------------------------------------------------


def rel(page: str, target: str) -> str:
    """A link from ``page`` to repo path ``target``."""
    depth = page.count("/")
    return "../" * depth + target


def link(page: str, target: str, text: str | None = None) -> str:
    return f"[{text or target}]({rel(page, target)})"


def counts_cell(pl: Place) -> str:
    bits = []
    if pl.rust:
        bits.append(f"{pl.rust} Rust")
    if pl.py:
        bits.append(f"{pl.py} Python")
    if pl.files:
        bits.append(f"{pl.files} files")
    return ", ".join(bits) or "–"


def scope(row: dict[str, object]) -> str:
    """The data and seeds a run covered, e.g. ``nq-10k, seeds 2024 9999``."""
    bits = []
    named = re.search(r"-(nq-\d+[km]|synthetic)-", str(row.get("result_file") or ""))
    if row.get("data"):
        bits.append(str(row["data"]))
    elif named:
        bits.append(named.group(1))
    seeds = row.get("seeds")
    if isinstance(seeds, list) and seeds:
        bits.append("seeds " + " ".join(str(s) for s in seeds))
    return ", ".join(bits) or "–"


def results_rows(page: str, rows: list[dict[str, object]]) -> list[str]:
    out = [
        "| Date (UTC) | Step | Data, seeds | Gate | Commit | Outcome | Result |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in sorted(rows, key=lambda r: str(r.get("utc", "")), reverse=True):
        rf = str(r.get("result_file") or "")
        res = link(page, rf, Path(rf).name) if rf and (ROOT / rf).exists() else (rf or "–")
        gate = str(r.get("gate") or "–").replace("|", "/")
        out.append(
            f"| {str(r.get('utc', ''))[:16].replace('T', ' ')} | `{step_of(r)}` | {scope(r)} | "
            f"{gate} | `{str(r.get('commit', ''))[:7]}` | {r.get('outcome')} | {res} |"
        )
    return out


def latest_per_step(page: str, rows: list[dict[str, object]]) -> list[str]:
    """The newest run of each (step, data, seeds): a later run of other seeds hides nothing."""
    last: dict[tuple[str, str], dict[str, object]] = {}
    for r in sorted(rows, key=lambda r: str(r.get("utc", ""))):
        last[(step_of(r), scope(r))] = r
    return results_rows(page, list(last.values()))


def part_page(
    p: Part, files: list[str], cmap: dict[str, int], rows: list[dict[str, object]]
) -> str:
    page = f"parts/{p.slug}/README.md"
    crates = sorted(c for c, n in cmap.items() if n == p.n)
    mine = owned(p.n)
    t = tag(p.n)
    lines = [
        HEADER + f"# Part {p.n}: {p.name}",
        "",
        f"**The claim it adds.** {p.claim}",
        "",
        f"- **Spec:** {p.spec} ({link(page, 'docs/SEVER-DB_SPECIFICATION.md', 'specification')})",
        f"- **Status:** {'frozen, tag `' + t + '`' if t else 'built, not frozen yet'}",
        f"- **Owned files:** {len(mine)} (`scripts/freeze.sh list {p.n}`)",
        f"- **Demo:** `{p.demo}`",
        "",
    ]
    for note in NOTES.get(p.n, []):
        lines.append(f"> {note}")
        lines.append("")
    lines += ["## Code", "", "| Crate | Path |", "|---|---|"]
    lines += [f"| `{c}` | {link(page, f'crates/{c}')} |" for c in crates]
    pkgs = sorted({f.split("/")[1] for f in mine if f.startswith("python/") and "/" in f[7:]})
    if pkgs:
        lines += ["", "| Python package | Path |", "|---|---|"]
        lines += [f"| `{k}` | {link(page, f'python/{k}')} |" for k in pkgs]
    other = sorted(
        {
            "/".join(f.split("/")[:2])
            for f in mine
            if not f.startswith(("crates/", "python/", "tests/"))
        }
    )
    if other:
        lines += ["", "Other files it owns: " + ", ".join(link(page, o) for o in other) + "."]
    places = test_places(p.n, files, crates)
    lines += ["", "## Tests", "", "| Where | Kind | Count |", "|---|---|---|"]
    lines += [f"| {link(page, pl.path)} | {pl.kind} | {counts_cell(pl)} |" for pl in places]
    mine_rows = [r for r in finished(rows) if part_of(r) == p.n]
    lines += ["", "## Results", ""]
    if mine_rows:
        lines += ["The latest outcome of each step:", ""]
        lines += latest_per_step(page, mine_rows)
        lines += [
            "",
            f"Every run of this part, newest first ({len(mine_rows)}; the full record is "
            f"{link(page, LEDGER, 'the run ledger')}):",
            "",
        ]
        lines += results_rows(page, mine_rows)
    else:
        lines.append("No run in the ledger.")
    reps = [r.format(n=p.n) for r in REPORTS if (ROOT / r.format(n=p.n)).exists()]
    lines += ["", "## Reports", ""]
    lines += [f"- {link(page, r)}" for r in reps] or ["None."]
    return "\n".join(lines) + "\n"


def parts_index() -> str:
    page = "parts/README.md"
    lines = [
        HEADER + "# The four parts",
        "",
        "SEVER-DB is built in four parts. Each one adds one claim and is then frozen "
        f"({link(page, 'CLAUDE.md', 'CLAUDE.md')} §6.1, Build §0.1). Each page lists the part's "
        "code, tests, results and reports. The code itself stays where the spec's layout puts "
        "it (§19.2).",
        "",
        "| Part | The claim it adds | Status | Page |",
        "|---|---|---|---|",
    ]
    for p in PARTS:
        t = tag(p.n)
        status = f"frozen (`{t}`)" if t else "built, not frozen"
        lines.append(f"| {p.n} {p.name} | {p.claim} | {status} | [{p.slug}]({p.slug}/README.md) |")
    lines += [
        "",
        f"Every test: {link(page, 'tests/README.md')}. Every result: "
        f"{link(page, 'docs/RESULTS.md')}.",
    ]
    return "\n".join(lines) + "\n"


def tests_index(files: list[str], cmap: dict[str, int]) -> str:
    page = "tests/README.md"
    lines = [
        HEADER + "# Every test, by part",
        "",
        "Where each part's tests live and how many there are. Test levels L1–L14 are defined in "
        "Build §2.1; each part's test plan says which level each kind belongs to. Counts are "
        "found by searching the source for `#[test]`, proptest cases and `def test_` (a "
        "parametrised test counts once), or are files for fuzz targets and red proofs.",
        "",
    ]
    total_r = total_p = 0
    for p in PARTS:
        crates = sorted(c for c, n in cmap.items() if n == p.n)
        places = test_places(p.n, files, crates)
        r = sum(x.rust for x in places)
        py = sum(x.py for x in places)
        total_r += r
        total_p += py
        lines += [
            f"## Part {p.n}: {p.name} ({r} Rust, {py} Python)",
            "",
            f"Part page: {link(page, f'parts/{p.slug}/README.md')}.",
            "",
            "| Where | Kind | Count |",
            "|---|---|---|",
        ]
        lines += [f"| {link(page, x.path)} | {x.kind} | {counts_cell(x)} |" for x in places]
        lines.append("")
    lines += ["## Shared (no part owns them)", "", "| Where | Count |", "|---|---|"]
    for d in SHARED_TESTS:
        fs = under(files, d)
        if fs:
            r, py = count(fs)
            lines.append(f"| {link(page, d)} | {r + py} test functions, {len(fs)} files |")
    lines += ["", f"**Total in the parts:** {total_r} Rust and {total_p} Python test functions."]
    return "\n".join(lines) + "\n"


def results_index(rows: list[dict[str, object]]) -> str:
    page = "docs/RESULTS.md"
    done = finished(rows)
    lines = [
        HEADER + "# Every result, by part",
        "",
        f"Each finished run in {link(page, LEDGER, 'the run ledger')}, grouped by part, newest "
        "first. A result file is written once by the gate and never edited (Build §2.5). "
        "Decisions about a result are in the overview's decision register (DB-N).",
        "",
    ]
    for p in PARTS:
        mine = [r for r in done if part_of(r) == p.n]
        lines += [f"## Part {p.n}: {p.name} ({len(mine)} runs)", ""]
        lines += [f"> {note}" for note in NOTES.get(p.n, [])]
        if NOTES.get(p.n):
            lines.append("")
        lines += results_rows(page, mine) if mine else ["No run."]
        lines.append("")
    rest = [r for r in done if part_of(r) is None]
    if rest:
        lines += ["## Other runs", ""]
        lines += results_rows(page, rest)
        lines.append("")
    in_ledger = {str(r.get("result_file")) for r in rows if r.get("result_file")}
    loose = sorted(
        f
        for f in tracked()
        if f.startswith("results/") and f.endswith(".json") and f not in in_ledger
    )
    if loose:
        lines += ["## Result files not named in the ledger", ""]
        lines += [f"- {link(page, f)}" for f in loose]
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def build() -> dict[str, str]:
    files = tracked()
    cmap = crate_parts()
    rows = ledger()
    out = {"parts/README.md": parts_index()}
    for p in PARTS:
        out[f"parts/{p.slug}/README.md"] = part_page(p, files, cmap, rows)
    out["tests/README.md"] = tests_index(files, cmap)
    out["docs/RESULTS.md"] = results_index(rows)
    if set(out) != set(OUTPUTS):
        raise SystemExit(f"refusing to write outside {OUTPUTS}")
    return out


def main(argv: list[str]) -> int:
    pages = build()
    if "--check" in argv:
        stale = [
            k
            for k, v in pages.items()
            if not (ROOT / k).exists() or (ROOT / k).read_text(encoding="utf-8") != v
        ]
        for k in stale:
            print(f"stale: {k}")
        print("index: OK" if not stale else "index: run python3 scripts/index.py")
        return 1 if stale else 0
    for k, v in pages.items():
        (ROOT / k).parent.mkdir(parents=True, exist_ok=True)
        (ROOT / k).write_text(v, encoding="utf-8")
        print(f"wrote {k}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
