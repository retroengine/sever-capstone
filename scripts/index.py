#!/usr/bin/env python3
"""Writes the navigation pages: one page per part, the test index and the result index (DB-115).

    python3 scripts/index.py            write parts/**/README.md, tests/README.md, docs/RESULTS.md
    python3 scripts/index.py --check    exit 1 if any of them is stale (writes nothing)

Read-only on its sources, which already decide ownership: ``scripts/freeze.sh list N`` (the files
each part owns), the ``PART`` map of ``tests/architecture/test_architecture.py`` (the crate of each
part), ``git ls-files`` and the run ledger. It changes no other file. The output carries no date,
so the same tree always gives the same pages.
"""

from __future__ import annotations

